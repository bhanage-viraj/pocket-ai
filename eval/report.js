#!/usr/bin/env node
// Builds a markdown comparison table from saved eval runs.
//   node eval/report.js                       # all runs in eval/results
//   node eval/report.js a.json b.json         # specific runs
//   node eval/report.js --write               # also write eval/RESULTS.md
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const argv = process.argv.slice(2);
const write = argv.includes('--write');
let files = argv.filter((a) => a.endsWith('.json'));
if (!files.length) {
  const dir = path.join(root, 'results');
  files = fs.readdirSync(dir)
    .filter((f) => f.endsWith('.json') && f !== 'baseline.json')
    .sort()
    .map((f) => path.join(dir, f));
}
const runs = files.map((f) => JSON.parse(fs.readFileSync(f, 'utf8')));
if (!runs.length) {
  console.error('No results yet. Run: npm run eval');
  process.exit(1);
}

const taskNames = [...new Set(runs.flatMap((r) => Object.keys(r.perTask)))];
const fieldCols = taskNames.flatMap((t) =>
  [...new Set(runs.flatMap((r) => Object.keys(r.perTask[t]?.fields || {})))].map((f) => [t, f]),
);
const short = (t) => t.replace(/^save_/, '');

const header = [
  'Run', 'Model', 'Intent acc', 'Field acc', 'Exact',
  ...taskNames.map((t) => `${short(t)} F1`),
  ...fieldCols.map(([t, f]) => `${short(t)}.${f}`),
  'p50 / p95 ms', 'tok/s', 'Cache hit',
];
const rows = runs.map((r) => [
  r.label, r.model, `**${r.intentAccuracy}%**`, `${r.fieldAccuracy}%`, `${r.exactMatch}%`,
  ...taskNames.map((t) => (r.perTask[t] ? `${r.perTask[t].f1}%` : '—')),
  ...fieldCols.map(([t, f]) => (r.perTask[t]?.fields?.[f] !== undefined ? `${r.perTask[t].fields[f]}%` : '—')),
  `${r.latencyMs.all.p50} / ${r.latencyMs.all.p95}`, `${r.genTokPerSec}`, `${r.cacheHitPct}%`,
]);

const md = [
  `| ${header.join(' | ')} |`,
  `|${header.map(() => '---').join('|')}|`,
  ...rows.map((r) => `| ${r.join(' | ')} |`),
].join('\n');

console.log(md);
if (write) {
  const out = path.join(root, 'RESULTS.md');
  fs.writeFileSync(
    out,
    `# Eval results\n\nGenerated by \`npm run eval:report -- --write\` on ${new Date().toISOString().slice(0, 10)}.\n` +
      `Each run = ${runs[runs.length - 1].n} labelled messages (English + Hinglish, incl. chat negatives).\n\n${md}\n`,
  );
  console.error(`\nWrote ${path.relative(process.cwd(), out)}`);
}
